// Copies the Tropicool Treats app stylesheet into the showcase so the video
// uses the app's real class names, tokens and component styling.
//
// Usage: node scripts/vendor-app-styles.mjs <path-to-tropicool-treats-teams>
// Default source: ../../whochandankatna/tropicool-treats-teams
//
// The copy is adapted for frame-accurate rendering:
// - Remote font and Tailwind imports are removed (fonts are bundled locally).
// - Viewport-width media queries are removed. In a render, the "viewport" is the
//   video frame, so the app's phone/tablet breakpoints would fire at the wrong
//   time. Each composition sets its own layout instead.
// - Page-level html/body/#root rules are removed so they do not fight Remotion.
// The application itself is never modified.
import { readFileSync, writeFileSync } from 'node:fs'
import { execSync } from 'node:child_process'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const appRoot = resolve(process.argv[2] ?? resolve(here, '../../../whochandankatna/tropicool-treats-teams'))
const source = readFileSync(resolve(appRoot, 'src/index.css'), 'utf8')

let commit = 'unknown'
try { commit = execSync('git rev-parse HEAD', { cwd: appRoot }).toString().trim() } catch { /* not a git checkout */ }

// Split the stylesheet into top-level blocks while respecting nested braces,
// strings and comments.
function topLevelBlocks(css) {
  const blocks = []
  let depth = 0, start = 0, i = 0
  while (i < css.length) {
    const ch = css[i]
    if (ch === '/' && css[i + 1] === '*') { const end = css.indexOf('*/', i + 2); i = end < 0 ? css.length : end + 2; continue }
    if (ch === '"' || ch === "'") { const q = ch; i++; while (i < css.length && css[i] !== q) { if (css[i] === '\\') i++; i++ } i++; continue }
    if (ch === ';' && depth === 0) { blocks.push(css.slice(start, i + 1)); start = i + 1 }
    else if (ch === '{') depth++
    else if (ch === '}') { depth--; if (depth === 0) { blocks.push(css.slice(start, i + 1)); start = i + 1 } }
    i++
  }
  if (css.slice(start).trim()) blocks.push(css.slice(start))
  return blocks
}

const stripComments = text => text.replace(/\/\*[\s\S]*?\*\//g, '').trim()
const dropped = { imports: 0, media: 0, page: 0 }
const kept = topLevelBlocks(source).filter(block => {
  const head = stripComments(block.slice(0, block.indexOf('{') < 0 ? block.length : block.indexOf('{')))
  if (head.startsWith('@import')) { dropped.imports++; return false }
  if (head.startsWith('@media') && /(max|min)-width|print/.test(head)) { dropped.media++; return false }
  const selectors = head.split(',').map(s => s.trim())
  if (!head.startsWith('@') && selectors.some(s => /^(html|body|#root)\b/.test(s))) { dropped.page++; return false }
  return true
})

const header = `/* Vendored from tropicool-treats-teams src/index.css at commit ${commit}.
   Generated by scripts/vendor-app-styles.mjs. Do not edit by hand; re-run the script.
   Removed: ${dropped.imports} imports, ${dropped.media} viewport/print media blocks, ${dropped.page} page-level rules. */\n`
writeFileSync(resolve(here, '../src/styles/tropicool-app.css'), header + kept.join('').trim() + '\n')
console.log(`Vendored ${kept.length} blocks from ${commit}`, dropped)
